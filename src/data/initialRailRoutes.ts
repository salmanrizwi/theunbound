export function findRoute(originId: string, destId: string): RailRoute | undefined {
  if (originId === destId) return undefined;
  
  // Direct match
  const direct = INITIAL_RAIL_ROUTES.find(r => r.originStationId === originId && r.destinationStationId === destId);
  if (direct) return direct;

  // Reverse match (routes are bi-directional in Shinkansen fare structure)
  const reverse = INITIAL_RAIL_ROUTES.find(r => r.originStationId === destId && r.destinationStationId === originId);
  if (reverse) {
    return {
      ...reverse,
      routeId: `JP-RT-${reverse.destinationStationName.toUpperCase()}-${reverse.originStationName.toUpperCase()}`,
      originStationId: originId,
      destinationStationId: destId,
      originStationName: reverse.destinationStationName,
      destinationStationName: reverse.originStationName
    };
  }

  return undefined;
}
